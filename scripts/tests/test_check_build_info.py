#!/usr/bin/env python3
"""test_check_build_info.py — 构建身份校验器与其接线（#515）

为什么需要：#515 的判据是「`run-dev` 在旧产物上运行时打明确 warning（含两侧 commit/时间），
不阻断启动」。两件事都可能静默退化：

1. **判定逻辑**：`commit` 与 HEAD 不同时必须报 stale 并给出两侧 sha 与 built_at；一致时
   必须安静。若谁把比对改成「只看文件存在」，本文件的一致性用例仍绿（它不存在），所以
   这里逐条锁 CLI 契约——退出码、stdout 的状态行、stderr 的 warning 文本。
2. **接线**：`run-dev.sh` / `run-dev.ps1` 必须真的调用校验器，且**不能**因为校验失败而
   中止（AC2 明确「不阻断」）。两个脚本都是 `exec`/`&` 启动长驻进程，进程级跑它们的
   唯一方式是真起栈，所以接线用静态断言（与 test_preflight_chaining 同思路）；判定
   逻辑本身由进程级 CLI 用例覆盖。

`--selftest` 的用例数也在这里钉住：`check_build_info.py --selftest` 提前 return 时
preflight 仍会打印 ok（它只看退出码），与 test_ci_scope 的 `EXPECTED_SELFTEST_CASES`
是同一条教训（selftest 缩水不算失败）。

跑法（被 preflight 的 unittest discovery 自动执行）：
    python3 -m unittest discover -s scripts/tests -k check_build_info -v
    python3 scripts/tests/test_check_build_info.py -v

退出码：0=通过，1=有失败。
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CHECKER = REPO_ROOT / "scripts" / "check_build_info.py"
RUN_DEV_SH = REPO_ROOT / "scripts" / "run-dev.sh"
RUN_DEV_PS1 = REPO_ROOT / "scripts" / "run-dev.ps1"

# 与 check_build_info.py 的 selftest 断言条数一致（改自测时同步改这里——两处都改是
# 有意的：`--selftest` 被砍掉一半用例时本断言红，而不是静默少验证）。
EXPECTED_SELFTEST_CASES = 22

STATUS_LINE_RE = re.compile(r"^build-info: status=(ok|stale|missing|unknown)\b")


def _shell_function_body(text: str, name: str) -> str | None:
    """取 `name() {` 到行首 `}` 之间的函数体（run-dev.sh 的既有形态）。"""
    match = re.search(rf"^{re.escape(name)}\(\) \{{\n(.*?)^\}}", text, re.MULTILINE | re.DOTALL)
    return match.group(1) if match else None


def run_checker(*args: str, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(CHECKER), *args],
        capture_output=True,
        text=True,
        cwd=cwd or REPO_ROOT,
        timeout=120,
        check=False,
    )


def run_git(root: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-c", "user.name=build-info-test",
         "-c", "user.email=test@example.invalid",
         "-c", "commit.gpgsign=false", *args],
        capture_output=True,
        text=True,
        cwd=root,
        timeout=60,
        check=False,
    )
    if result.returncode != 0:
        raise AssertionError(f"git {' '.join(args)} failed: {result.stderr}")
    return result.stdout.strip()


class BuildInfoCliTest(unittest.TestCase):
    """进程级契约：命令行的退出码、状态行、warning 文案。"""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="dz_build_info_cli_")
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name) / "repo"
        self.root.mkdir()
        run_git(self.root, "init", "-q", "-b", "main")
        (self.root / "README.md").write_text("# baseline\n", encoding="utf-8")
        run_git(self.root, "add", "README.md")
        run_git(self.root, "commit", "-q", "-m", "chore: baseline")
        self.head = run_git(self.root, "rev-parse", "HEAD")
        self.info = Path(self._tmp.name) / "install" / "BUILD_INFO"

    def write_info(self, *, commit: str, dirty: str = "0", built_at: str = "2026-01-01T00:00:00Z") -> None:
        self.info.parent.mkdir(parents=True, exist_ok=True)
        self.info.write_text(
            "# dztrader build identity | generated by the build, do not edit (#515)\n"
            f"commit={commit}\ndirty={dirty}\nbuilt_at={built_at}\n"
            "version=0.1.0\nconfig=Release\n",
            encoding="utf-8",
        )

    def check(self) -> subprocess.CompletedProcess[str]:
        return run_checker("check", "--info", str(self.info), "--repo", str(self.root))

    def test_matching_commit_is_ok_and_quiet(self) -> None:
        self.write_info(commit=self.head)
        result = self.check()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        status_lines = [line for line in result.stdout.splitlines() if STATUS_LINE_RE.match(line)]
        self.assertEqual(len(status_lines), 1, result.stdout)
        self.assertIn("status=ok", status_lines[0])
        self.assertEqual(result.stderr, "", f"ok case must be silent on stderr: {result.stderr!r}")

    def test_stale_commit_warns_with_both_shas_and_built_at(self) -> None:
        self.write_info(commit="1" * 40, built_at="2026-02-03T04:05:06Z")
        result = self.check()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("status=stale", result.stdout)
        combined = result.stdout + result.stderr
        self.assertIn("1" * 12, combined)
        self.assertIn(self.head[:12], combined)
        self.assertIn("2026-02-03T04:05:06Z", combined)
        self.assertIn("warning:", result.stderr)

    def test_missing_info_warns_and_exits_nonzero(self) -> None:
        result = self.check()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("status=missing", result.stdout)
        self.assertIn("warning:", result.stderr)

    def test_unreadable_info_is_not_reported_as_ok(self) -> None:
        self.info.parent.mkdir(parents=True, exist_ok=True)
        self.info.write_text("version=0.1.0\n", encoding="utf-8")
        result = self.check()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertNotIn("status=ok", result.stdout)

    def test_dirty_build_is_ok_with_note(self) -> None:
        self.write_info(commit=self.head, dirty="1")
        result = self.check()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("status=ok", result.stdout)
        self.assertIn("note:", result.stderr)

    def test_default_info_path_points_at_release_install_tree(self) -> None:
        """无 --info 时按平台推路径：install/<plat>/x86_64/Release/BUILD_INFO。"""
        result = run_checker("check", "--repo", str(self.root))
        self.assertIn("status=missing", result.stdout)
        # 报错文案里必须带出它查找的路径，否则「为什么 missing」无从判断。
        self.assertRegex(result.stderr, r"install[/\\][^ ]*x86_64[/\\]Release[/\\]BUILD_INFO")

    def test_selftest_passes_with_expected_case_count(self) -> None:
        result = run_checker("--selftest")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        match = re.search(r"selftest: (\d+) cases", result.stdout)
        self.assertIsNotNone(match, result.stdout)
        assert match is not None
        self.assertEqual(
            int(match.group(1)),
            EXPECTED_SELFTEST_CASES,
            "check_build_info.py --selftest 的用例数变了：确认是有意新增/删除后同步本常量"
            "（提前 return 会让 preflight 静默少验证）",
        )

    def test_unknown_command_is_a_usage_error(self) -> None:
        result = run_checker()
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)

    def test_bad_repo_path_is_an_env_error(self) -> None:
        self.write_info(commit=self.head)
        result = run_checker(
            "check", "--info", str(self.info), "--repo", str(Path(self._tmp.name) / "nope")
        )
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)


class RunDevWiringTest(unittest.TestCase):
    """两个启动脚本都必须调用校验器，且都不能因校验失败中止启动（AC2）。"""

    def test_posix_run_dev_invokes_checker_and_tolerates_failure(self) -> None:
        text = RUN_DEV_SH.read_text(encoding="utf-8")
        self.assertIn("check_build_info.py", text, "run-dev.sh 未接入构建身份校验")
        self.assertIn("BUILD_INFO", text, "run-dev.sh 未按 install 树定位 BUILD_INFO")
        # 不阻断（`set -euo pipefail` 下裸调用会让脚本在旧产物上直接退出——正是 AC2
        # 禁止的行为）。调用本身是续行的，所以按**所在函数体**断言，不按单行匹配。
        body = _shell_function_body(text, "check_build_identity")
        self.assertIsNotNone(body, "run-dev.sh 缺 check_build_identity 函数")
        assert body is not None
        self.assertIn("check_build_info.py", body, body)
        self.assertTrue(
            "|| rc=$?" in body or "|| true" in body,
            f"check_build_identity 的校验调用没有吞掉失败（set -e 会中止启动）:\n{body}",
        )
        self.assertRegex(
            body, r"return 0\s*$", "check_build_identity 必须以 0 返回（校验永不阻断启动）"
        )

    def test_windows_run_dev_invokes_checker_and_restores_exit_code(self) -> None:
        text = RUN_DEV_PS1.read_text(encoding="utf-8")
        self.assertIn("check_build_info.py", text, "run-dev.ps1 未接入构建身份校验")
        self.assertIn("BUILD_INFO", text, "run-dev.ps1 未按 install 树定位 BUILD_INFO")
        # PowerShell 侧不阻断的形态：判定后把 $LASTEXITCODE 复位，避免旧的失败码
        # 漏到后续 & $master_exe 之外的地方（$ErrorActionPreference='Stop' 下不必
        # 额外 try/catch，但退出码必须显式清）。
        self.assertRegex(
            text,
            r"\$global:LASTEXITCODE\s*=\s*0",
            "run-dev.ps1 未在校验后复位 $LASTEXITCODE（失败码会污染后续步骤）",
        )


if __name__ == "__main__":
    unittest.main(verbosity=2)
